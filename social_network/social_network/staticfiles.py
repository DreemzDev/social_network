"""Адрес статики меняется вместе с самим файлом.

Зачем
-----
Статику отдаёт `staticfiles` из `STATIC_ROOT`, и в ответе есть только
`Last-Modified`: ни `ETag`, ни `Cache-Control`. Для браузера это разрешение
на «эвристическое» кеширование — свежесть он считает сам, примерно как 10%
от возраста файла. Скрипт, лежавший без правок неделю, кешируется на часы, и
всё это время сервер о нём даже не спрашивают: в замерах через CDP повторный
заход на страницу давал `transferSize: 0` — файл брался из кеша молча.

На этом уже сгорела починка удаления в корзину (коммит ccf0d250): сервер
отдавал исправленный `fm-actions.js`, а браузер продолжал выполнять
прежний, и для пользователя «ничего не изменилось». Лечилось это только
Ctrl+F5, о котором сотрудникам знать неоткуда.

Поэтому `{% static %}` дописывает к адресу время правки файла:

    /app/static/js/fm-actions.js?v=1786443760

Правка файла — новый адрес — новый запрос, без всяких Ctrl+F5. Пока файл не
менялся, адрес прежний, и кеш работает как задумано. HTML при этом не
кешируется: у обычных ответов Django нет ни `Last-Modified`, ни `Expires`,
эвристике не от чего считать, — значит новую версию адреса страница получит
сразу.

Почему не `ManifestStaticFilesStorage`
--------------------------------------
Он требует `collectstatic`, а здесь `STATIC_ROOT` — он же каталог исходной
статики (`STATICFILES_FINDERS` — только `CompressorFinder`, он читает прямо
оттуда). Сбор файлов «сам в себя» этой схеме противопоказан, а версия в
запросе даёт тот же результат без манифеста и без отдельного шага сборки.
"""
import os

from django.contrib.staticfiles.storage import StaticFilesStorage


class VersionedStaticFilesStorage(StaticFilesStorage):
    """`StaticFilesStorage` + `?v=<время правки>` в адресе."""

    def url(self, name):
        url = super().url(name)

        try:
            version = int(os.path.getmtime(self.path(name)))
        except Exception:
            # Файл может лежать не в STATIC_ROOT (статика сторонних
            # приложений) или не существовать вовсе — на такие ссылки
            # шаблон и раньше отдавал адрес как есть. Версия — приятное
            # дополнение, а не условие работы: разваливать из-за неё
            # рендер страницы нельзя.
            return url

        return '{}{}v={}'.format(url, '&' if '?' in url else '?', version)
