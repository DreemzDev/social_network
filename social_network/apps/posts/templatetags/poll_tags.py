"""Итоги опроса для шаблона.

Отдельный тег, а не расчёт во вьюхе: блок опроса включается из четырёх мест
(лента, «Моя страница», отдельная запись, довставка новых записей), и класть
результаты в контекст пришлось бы в каждой вьюхе — забытая строчка означала
бы пустой опрос без единой ошибки в логах.
"""
from django import template

register = template.Library()


@register.simple_tag
def poll_results(poll, user):
    """Варианты со счётчиками и отметкой своего голоса."""
    return poll.results_for(user)
